export interface FillBlankQuestion {
  id: string;
  type: 'fill_blank';
  chapter: 1 | 2 | 3 | 4 | 5;
  category: string;
  sentence: string; // contains [BLANK_1], [BLANK_2] etc.
  blanks: {
    index: number;
    acceptableAnswers: string[];
    primaryAnswer: string;
  }[];
  explanation?: string;
}

export interface WordBankSetQuestion {
  id: string;
  type: 'word_bank';
  chapter: 1 | 2 | 3 | 4 | 5;
  category: string;
  wordBank: string[];
  subQuestions: {
    subId: number;
    sentence: string; // contains [BLANK]
    acceptableAnswers: string[];
    correctAnswer: string;
  }[];
  explanation?: string;
}

export interface TrueFalseQuestion {
  id: string;
  type: 'true_false';
  chapter: 1 | 2 | 3 | 4 | 5;
  category: string;
  statement: string;
  isCorrect: boolean; // true for ✓, false for 
  explanation?: string;
}

